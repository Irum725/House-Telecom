"""Jobs / Scheduler & Interest Regions API router."""

import os
from pathlib import Path
from typing import Optional

from fastapi import APIRouter, Body, Depends, HTTPException, Response
from sqlalchemy import select
from sqlalchemy.orm import Session

from backend.jobs import format_region_code, run_all_active_regions, run_weekly_pipeline
from shared.database import get_db
from shared.models import InterestRegion, ReportRun
from shared.schemas import (
    InterestRegionCreate,
    InterestRegionItem,
    InterestRegionListResponse,
    JobTriggerRequest,
    JobTriggerResponse,
    ReportListResponse,
    ReportRunItem,
)

router = APIRouter(prefix="/api/jobs", tags=["jobs"])


def _has_real_service_key() -> tuple[bool, Optional[str]]:
    key = os.getenv("DATA_GO_KR_SERVICE_KEY", "").strip()
    if key and key != "your_data_go_kr_service_key_here":
        return True, key
    return False, None


def _get_report_output_dir() -> Path:
    return Path(os.getenv("REPORT_OUTPUT_DIR", "./data/reports"))


@router.get("/interest-regions", response_model=InterestRegionListResponse)
def list_interest_regions(db: Session = Depends(get_db)) -> InterestRegionListResponse:
    """List all configured scheduler interest regions."""
    rows = list(db.scalars(select(InterestRegion).order_by(InterestRegion.id.asc())).all())
    items = [InterestRegionItem.model_validate(r) for r in rows]
    return InterestRegionListResponse(items=items, total=len(items))


@router.post("/interest-regions", response_model=InterestRegionItem, status_code=201)
def create_interest_region(
    payload: InterestRegionCreate,
    db: Session = Depends(get_db),
) -> InterestRegionItem:
    """Register a new interest region for scheduled reporting."""
    region = InterestRegion(
        sigungu_cd=payload.sigungu_cd,
        bjdong_cd=payload.bjdong_cd,
        name=payload.name,
        is_active=payload.is_active,
        cron_expr=payload.cron_expr,
    )
    db.add(region)
    db.commit()
    db.refresh(region)
    return InterestRegionItem.model_validate(region)


@router.delete("/interest-regions/{region_id}", status_code=204)
def delete_interest_region(
    region_id: int,
    db: Session = Depends(get_db),
) -> Response:
    """Delete an interest region by ID."""
    region = db.get(InterestRegion, region_id)
    if region is None:
        raise HTTPException(status_code=404, detail=f"InterestRegion not found: {region_id}")
    db.delete(region)
    db.commit()
    return Response(status_code=204)


@router.get("/runs", response_model=ReportListResponse)
def list_job_report_runs(
    region_code: Optional[str] = None,
    db: Session = Depends(get_db),
) -> ReportListResponse:
    """List report runs generated by scheduler or manual triggers."""
    stmt = select(ReportRun).order_by(ReportRun.run_at.desc(), ReportRun.id.desc())
    if region_code:
        stmt = stmt.where(ReportRun.region_code.like(f"{region_code}%"))
    rows = list(db.scalars(stmt).all())
    items = [ReportRunItem.model_validate(r) for r in rows]
    return ReportListResponse(items=items, total=len(items))


@router.post("/trigger", response_model=JobTriggerResponse)
def trigger_jobs(
    payload: Optional[JobTriggerRequest] = Body(default=None),
    db: Session = Depends(get_db),
) -> JobTriggerResponse:
    """Manually trigger collection + stage evaluation + diff + Excel/PDF report generation."""
    has_key, service_key = _has_real_service_key()
    use_fixture = not has_key
    output_dir = _get_report_output_dir()

    runs: list[ReportRun] = []

    if payload is not None and payload.interest_region_id is not None:
        ir = db.get(InterestRegion, payload.interest_region_id)
        if ir is None:
            raise HTTPException(
                status_code=404,
                detail=f"InterestRegion not found: {payload.interest_region_id}",
            )
        code = format_region_code(ir.sigungu_cd, ir.bjdong_cd)
        runs.append(
            run_weekly_pipeline(
                code,
                db=db,
                use_fixture=use_fixture,
                output_dir=output_dir,
                service_key=service_key,
            )
        )
    elif payload is not None and payload.sigungu_cd is not None:
        code = format_region_code(payload.sigungu_cd, payload.bjdong_cd)
        runs.append(
            run_weekly_pipeline(
                code,
                db=db,
                use_fixture=use_fixture,
                output_dir=output_dir,
                service_key=service_key,
            )
        )
    else:
        runs = run_all_active_regions(
            db=db,
            use_fixture=use_fixture,
            output_dir=output_dir,
            service_key=service_key,
        )

    return JobTriggerResponse(
        status="completed",
        triggered_regions=[r.region_code for r in runs],
        report_run_ids=[r.id for r in runs],
        message=f"Executed {len(runs)} report run(s)",
    )
